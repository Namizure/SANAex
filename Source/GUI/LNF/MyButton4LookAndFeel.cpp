void MyButton4LookAndFeel::drawButtonBackground(juce::Graphics& g, juce::Button& button, const juce::Colour&,
	bool isHighlighted, bool isDown)
{
	auto area = button.getLocalBounds().toFloat().reduced(3.0f);
	juce::Path shape;
	shape.addRoundedRectangle(area, 0.0f);


	if (button.getToggleState())
	{
		g.setImageResamplingQuality(juce::Graphics::lowResamplingQuality);
		g.drawImage(onSprite, area, juce::RectanglePlacement::stretchToFit);
		g.setImageResamplingQuality(juce::Graphics::mediumResamplingQuality);
	}
	else
	{
		g.setImageResamplingQuality(juce::Graphics::lowResamplingQuality);
		g.drawImage(normalSprite, area, juce::RectanglePlacement::stretchToFit);
		g.setImageResamplingQuality(juce::Graphics::mediumResamplingQuality);
	}

	if (isDown)
	{
		g.setColour(juce::Colours::black.withAlpha(0.1f));
		g.fillPath(shape);

		if (!button.getClickingTogglesState())
		{
			float strokeWidth = 1.5f;
			auto strokeBounds = area.reduced(strokeWidth * 0.5f);
			float x = strokeBounds.getX();
			float y = strokeBounds.getY();
			float width = strokeBounds.getWidth();
			float height = strokeBounds.getHeight();

			juce::Path highlightPath;
			highlightPath.startNewSubPath(x, y + height);
			highlightPath.lineTo(x, y);
			highlightPath.lineTo(x + width, y);

			juce::Path shadowPath;
			shadowPath.startNewSubPath(x + width, y);
			shadowPath.lineTo(x + width, y + height);
			shadowPath.lineTo(x, y + height);

			juce::Colour lightColour(206, 203, 210);
			juce::Colour darkColour(98, 97, 100);

			g.setColour(darkColour);
			g.strokePath(highlightPath, juce::PathStrokeType(strokeWidth));

			g.setColour(lightColour);
			g.strokePath(shadowPath, juce::PathStrokeType(strokeWidth));
		}
	}
	else if (isHighlighted)
	{
		g.setColour(juce::Colours::white.withAlpha(0.05f));
		g.fillPath(shape);
	}
}

void MyButton4LookAndFeel::drawButtonText(juce::Graphics& g, juce::TextButton& button, bool, bool)
{
	g.setFont(ManekiText::font(button, juce::FontOptions(18.0f)));
	g.setColour(button.getToggleState() ? juce::Colour(0xff202128) : juce::Colour(0xff202128));
	g.drawFittedText(button.getButtonText(), ManekiText::area(button, button.getLocalBounds().reduced(7, 0)),
		ManekiText::justification(button, juce::Justification::centred), 2);
}
